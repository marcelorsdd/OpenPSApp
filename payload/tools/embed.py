#!/usr/bin/env python3
"""Generates C++ sources that embed build outputs into the payload ELF.

  embed.py web  <ui/dist dir>  <out.cpp>                UI bundle (text gzip'd) -> openpsapp::web::kAssets
  embed.py tile <tile .pkg> <param.json> <out.cpp>     tile PKG + its title id and deeplink port

A missing input still produces a valid source: a placeholder page for the UI,
an empty PKG for the tile (the payload then skips the install).
"""
import gzip
import json
import sys
from pathlib import Path
from urllib.parse import urlparse

CONTENT_TYPES = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".json": "application/json",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".ico": "image/x-icon",
    ".woff2": "font/woff2",
    ".txt": "text/plain; charset=utf-8",
}
COMPRESSIBLE = {".html", ".js", ".css", ".json", ".svg", ".txt"}

PLACEHOLDER = b"""<!doctype html><meta charset="utf-8"><title>OpenPSApp</title>
<body style="background:#0b0f1a;color:#e8ecf5;font:20px sans-serif;padding:48px">
<h1>OpenPSApp</h1><p>UI not built into this payload. Run <code>make ui</code> and rebuild.</p>
<p>The API is up: <a style="color:#2f7cf6" href="/api/v1/games">/api/v1/games</a></p></body>"""


def byte_array(name: str, data: bytes) -> str:
    body = ",".join(map(str, data)) if data else "0"
    return f"const unsigned char {name}[] = {{{body}}};\n"


def web(dist: Path, out: Path) -> None:
    files = []
    if (dist / "index.html").is_file():
        for path in sorted(p for p in dist.rglob("*") if p.is_file()):
            files.append(("/" + path.relative_to(dist).as_posix(), path.suffix, path.read_bytes()))
    else:
        files.append(("/index.html", ".html", PLACEHOLDER))

    parts = [
        "// GENERATED by payload/tools/embed.py from ui/dist — do not edit.\n",
        '#include "routes/web.hpp"\n\nnamespace openpsapp::web {\n\n',
    ]
    entries = []
    for i, (url, suffix, data) in enumerate(files):
        gz = suffix in COMPRESSIBLE
        payload = gzip.compress(data, compresslevel=9, mtime=0) if gz else data
        parts.append("static " + byte_array(f"kData{i}", payload))
        ctype = CONTENT_TYPES.get(suffix, "application/octet-stream")
        entries.append(f'    {{"{url}", "{ctype}", kData{i}, {len(payload)}u, {"true" if gz else "false"}}},\n')
    parts.append("\nconst Asset kAssets[] = {\n" + "".join(entries) + "};\n")
    parts.append(f"const unsigned kAssetCount = {len(entries)}u;\n\n}} // namespace openpsapp::web\n")
    out.write_text("".join(parts))
    total = sum(len(d) for _, _, d in files)
    print(f"embed: {len(files)} UI files ({total} bytes) -> {out}")


def tile(pkg: Path, param_json: Path, out: Path) -> None:
    data = pkg.read_bytes() if pkg.is_file() else b""
    param = json.loads(param_json.read_text())
    port = urlparse(param["deeplinkUri"]).port
    out.write_text(
        "// GENERATED by payload/tools/embed.py from tile/ — do not edit.\n"
        '#include "services/tile.hpp"\n\nnamespace openpsapp::tile {\n\n'
        + byte_array("kPkg", data)
        + f"const unsigned kPkgSize = {len(data)}u;\n"
        + f'const char kTitleId[] = "{param["titleId"]}";\n'
        + f"const int kDeeplinkPort = {port};\n\n}} // namespace openpsapp::tile\n"
    )
    print(f"embed: tile PKG ({len(data)} bytes{'' if data else ', none built'}) -> {out}")


def main() -> int:
    args = sys.argv[1:]
    if args[:1] == ["web"] and len(args) == 3:
        Path(args[2]).parent.mkdir(parents=True, exist_ok=True)
        web(Path(args[1]), Path(args[2]))
    elif args[:1] == ["tile"] and len(args) == 4:
        Path(args[3]).parent.mkdir(parents=True, exist_ok=True)
        tile(Path(args[1]), Path(args[2]), Path(args[3]))
    else:
        print(__doc__, file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
